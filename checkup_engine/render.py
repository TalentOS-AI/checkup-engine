"""Render a report dict to a self-contained HTML page (all values escaped)."""

from __future__ import annotations

from html import escape

T = {
    "zh": {"title": "AI 体检报告", "overall": "综合得分", "recs": "最值得先交给 AI 的事", "evidence": "证据",
           "dims": "五个维度", "pass": "通过", "fail": "待改进", "pages": "本次读取的公开页面", "notes": "说明",
           "cost": "本次模型成本", "time": "耗时", "hours": "预计每月节省工时（估算）", "mode_offline":
           "离线模式：建议来自公开评分规则，未调用大模型。", "how": "AI 怎么帮", "qa_dropped": "质检删除的建议",
           "footer": "由 TalentOS checkup-engine 生成"},
    "en": {"title": "AI Checkup Report", "overall": "Overall score", "recs": "Top things to hand to AI first",
           "evidence": "Evidence", "dims": "Five dimensions", "pass": "Pass", "fail": "To improve",
           "pages": "Public pages read", "notes": "Notes", "cost": "Model cost", "time": "Time",
           "hours": "Est. hours saved / month (estimate)", "mode_offline":
           "Offline mode: recommendations come from the public rubric; no LLM was called.",
           "how": "How AI helps", "qa_dropped": "Recommendations removed by QA",
           "footer": "Generated by TalentOS checkup-engine"},
}

CSS = """
:root{--ink:#14161A;--muted:#5B6270;--line:#E3E5EA;--bg:#F7F7F5;--accent:#C2410C;--ok:#1E8E4E;--bad:#A3412A}
*{box-sizing:border-box}body{margin:0;font:16px/1.6 -apple-system,BlinkMacSystemFont,"Segoe UI","PingFang SC",
"Microsoft YaHei",Helvetica,Arial,sans-serif;color:var(--ink);background:#fff}
.wrap{max-width:880px;margin:0 auto;padding:40px 20px}h1{font-size:30px;margin:0 0 4px}h2{font-size:22px;margin:40px 0 16px}
.muted{color:var(--muted)}.score{display:flex;gap:28px;align-items:center;margin:28px 0;padding:24px;background:var(--bg);
border-radius:10px}.big{font-size:56px;font-weight:800;line-height:1}.bar{height:8px;background:var(--line);border-radius:4px;
overflow:hidden}.bar i{display:block;height:100%;background:var(--accent)}.dim{margin:14px 0}.dimh{display:flex;
justify-content:space-between;font-weight:600}.rec{border-left:3px solid var(--accent);padding:14px 18px;margin:16px 0;
background:var(--bg);border-radius:6px}.rec h3{margin:0 0 6px;font-size:18px}.rec p{margin:6px 0}a{color:var(--ink);
text-decoration-color:var(--accent);text-underline-offset:3px;word-break:break-all}details{margin:6px 0 12px}
summary{cursor:pointer;color:var(--muted)}ul.checks{list-style:none;padding:0;margin:8px 0}ul.checks li{padding:4px 0;
border-bottom:1px solid var(--line);font-size:14px}.ok{color:var(--ok)}.bad{color:var(--bad)}.foot{margin-top:48px;
font-size:13px;color:var(--muted);border-top:1px solid var(--line);padding-top:16px}
"""


def _a(url: str) -> str:
    u = str(url or "")
    if not u.startswith(("http://", "https://")):
        return escape(u)
    return f'<a href="{escape(u, quote=True)}" rel="nofollow noopener" target="_blank">{escape(u)}</a>'


def render_html(report: dict) -> str:
    lang = report.get("lang", "zh")
    t = T.get(lang, T["en"])
    e = escape
    label = "label_zh" if lang == "zh" else "label_en"
    out = [f'<!doctype html><html lang="{"zh-CN" if lang == "zh" else "en"}"><head><meta charset="utf-8">',
           '<meta name="viewport" content="width=device-width,initial-scale=1">',
           '<meta name="robots" content="noindex">',
           f"<title>{e(t['title'])} · {e(report['final_url'])}</title><style>{CSS}</style></head><body><div class=wrap>",
           f"<h1>{e(t['title'])}</h1><p class=muted>{_a(report['final_url'])} · {e(report['generated_at'])}</p>"]
    if report.get("business_summary"):
        out.append(f"<p>{e(report['business_summary'])}</p>")
    s = report["scores"]
    out.append(f"<div class=score><div><div class=muted>{e(t['overall'])}</div><div class=big>{int(s['overall'])}</div>"
               f"</div><p>{e(report['summary'])}</p></div>")
    if report.get("mode") == "offline":
        out.append(f"<p class=muted>{e(t['mode_offline'])}</p>")
    out.append(f"<h2>{e(t['recs'])}</h2>")
    for i, r in enumerate(report["recommendations"], 1):
        hours = r.get("est_hours_saved_per_month")
        out.append(f"<div class=rec><h3>{i}. {e(r['title'])}</h3><p>{e(r['why'])}</p>"
                   f"<p><strong>{e(t['how'])}：</strong>{e(r['how_ai_helps'])}</p>" if lang == "zh" else
                   f"<div class=rec><h3>{i}. {e(r['title'])}</h3><p>{e(r['why'])}</p>"
                   f"<p><strong>{e(t['how'])}:</strong> {e(r['how_ai_helps'])}</p>")
        if hours is not None:
            out.append(f"<p class=muted>{e(t['hours'])}: {e(str(hours))}</p>")
        out.append(f"<p class=muted>{e(t['evidence'])}: {_a(r['evidence_url'])}</p></div>")
    if report.get("qa", {}).get("dropped"):
        out.append(f"<details><summary>{e(t['qa_dropped'])} ({len(report['qa']['dropped'])})</summary><ul>")
        out += [f"<li>{e(d.get('title', ''))} — {e(d.get('reason', ''))}</li>" for d in report["qa"]["dropped"]]
        out.append("</ul></details>")
    out.append(f"<h2>{e(t['dims'])}</h2>")
    for d in s["dimensions"]:
        sc = int(d["score"])
        out.append(f"<div class=dim><div class=dimh><span>{e(d[label])}</span><span>{sc}</span></div>"
                   f"<div class=bar><i style='width:{sc}%'></i></div><details><summary>{len(d['checks'])} checks</summary>"
                   "<ul class=checks>")
        for c in d["checks"]:
            mark = f"<span class=ok>✓ {e(t['pass'])}</span>" if c["passed"] else f"<span class=bad>✗ {e(t['fail'])}</span>"
            out.append(f"<li>{mark} · {e(c.get(label, c['id']))} — <span class=muted>{e(c['detail'])}</span></li>")
        out.append("</ul></details></div>")
    col = report["collection"]
    out.append(f"<h2>{e(t['pages'])}</h2><ul>")
    out += [f"<li>{e(p.get('role') or '')}: {_a(p['url'])}</li>" for p in col["pages"]]
    out.append("</ul>")
    if col.get("notes"):
        out.append(f"<h2>{e(t['notes'])}</h2><ul>" + "".join(f"<li>{e(n)}</li>" for n in col["notes"]) + "</ul>")
    cost = report["cost"]
    secs = report.get("timing", {}).get("total_ms", 0) / 1000
    out.append(f"<p class=muted>{e(t['cost'])}: ${cost['est_cost_usd']:.4f} · {cost['llm_calls']} LLM calls · "
               f"{e(t['time'])}: {secs:.0f}s · rubric v{e(report['rubric_version'])}</p>")
    out.append(f"<div class=foot>{e(report['disclaimer'])}<br>{e(t['footer'])} v{e(report['engine_version'])} · "
               '<a href="https://github.com/TalentOS-AI/checkup-engine">github.com/TalentOS-AI/checkup-engine</a> · '
               '<a href="https://www.agentbay.asia">TalentOS</a></div></div></body></html>')
    return "".join(out)
